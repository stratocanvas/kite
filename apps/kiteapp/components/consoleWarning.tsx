"use client";

import { useEffect } from "react";

export default function ConsoleWarning() {
	useEffect(() => {
		const warningMessage = `                       
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@@@      @@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@@@@        @@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@@@           @@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@@@@           @@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@@@            @@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@@@@           @@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@@@            @@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
@@           @@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
           @@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
        @@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@                 
      @@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@  
      
    `;
		const emitWarning = () => {
			console.log(
				`%c${warningMessage}`,
				"font-size: 10px;",
			);
		};

		emitWarning();

		// 개발자 도구가 열릴 때마다 경고 메시지를 다시 출력
		window.addEventListener("devtoolschange", (event) => {
			if (event.detail.isOpen) {
				emitWarning();
			}
		});
	}, []);

	return null;
}
